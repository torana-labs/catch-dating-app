#!/usr/bin/env bash
# Print a complete infra/firebase/terraform.tfvars from the live Firebase apps.
#
#   FIREBASE_ACCESS_TOKEN=... infra/scripts/firebase_android_inventory.sh \
#     [--play play.jsonl] prod=catch-dating-app-64e51 staging=catchdates-staging dev=catchdates-dev
#
# Read-only. Lists each project's ACTIVE Android apps through the Firebase
# Management API, reads every app the way Terraform does (androidApps.get),
# keeps each hash list in the order the API returns it, and appends any Play
# app-signing fingerprint from --play (output of play_signing_fingerprints.sh)
# that is not registered yet. The result makes the first plan show exactly the
# new fingerprints and nothing else.
set -euo pipefail

token="${FIREBASE_ACCESS_TOKEN:?FIREBASE_ACCESS_TOKEN must hold a Firebase read access token}"
play_file=""
if [[ "${1:-}" == "--play" ]]; then
  play_file="${2:?--play needs a file}"
  shift 2
fi
[[ $# -gt 0 ]] || { echo "usage: firebase_android_inventory.sh [--play file] <env>=<project>..." >&2; exit 2; }

api="https://firebase.googleapis.com/v1beta1"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

get() {
  curl --fail --silent --show-error --retry 3 \
    --header "Authorization: Bearer $token" "$1"
}

: > "$work/apps.jsonl"
for pair in "$@"; do
  environment="${pair%%=*}"
  project="${pair#*=}"
  [[ "$environment" =~ ^(dev|staging|prod)$ && -n "$project" && "$project" != "$pair" ]] || {
    echo "Bad environment mapping: $pair" >&2; exit 2; }
  get "$api/projects/$project/androidApps?pageSize=100" > "$work/list.json"
  if [[ "$(jq -r '.nextPageToken // ""' "$work/list.json")" != "" ]]; then
    echo "$project has more than 100 Android apps; refusing a partial inventory." >&2
    exit 1
  fi
  for app_id in $(jq -r '.apps[]? | select((.state // "ACTIVE") == "ACTIVE") | .appId' "$work/list.json"); do
    get "$api/projects/$project/androidApps/$app_id" |
      jq -c --arg environment "$environment" --arg project "$project" '{
        environment: $environment, project: $project, app_id: .appId,
        package_name: .packageName, display_name: .displayName,
        sha1_hashes: (.sha1Hashes // []), sha256_hashes: (.sha256Hashes // [])
      }' >> "$work/apps.jsonl"
  done
done

# Role comes from the package name: com.catchdates.host* is Host and
# com.catchdates.app* is Consumer. Anything else is reported, not managed.
jq -s '
  map(. + {role: (if (.package_name | test("^com\\.catchdates\\.host(\\.|$)")) then "host"
                  elif (.package_name | test("^com\\.catchdates\\.app(\\.|$)")) then "consumer"
                  else null end)})
' "$work/apps.jsonl" > "$work/apps.json"

jq -r '.[] | select(.role == null) | "Skipping unrecognised Android app \(.package_name) (\(.app_id)) in \(.project)."' \
  "$work/apps.json" >&2
if [[ "$(jq '[.[] | select(.role != null) | "\(.environment)-\(.role)"] | (length != (unique | length))' "$work/apps.json")" == "true" ]]; then
  echo "Two active apps map to the same <environment>-<role> key; resolve this in Firebase first." >&2
  exit 1
fi

if [[ -n "$play_file" ]]; then
  jq -s '.' "$play_file" > "$work/play.json"
else
  echo '[]' > "$work/play.json"
fi

jq -r --slurpfile play "$work/play.json" '
  def append_missing($existing; $new):
    reduce $new[] as $hash ($existing;
      if (map(ascii_downcase) | index($hash | ascii_downcase)) then . else . + [$hash] end);
  def hcl_list: if length == 0 then "[]" else "[\n" + (map("      \"\(.)\",\n") | join("")) + "    ]" end;
  def order: {prod: 0, staging: 1, dev: 2}[.environment] * 10 + {consumer: 0, host: 1}[.role];

  [.[] | select(.role != null)] | sort_by(order) | map(
    . as $app
    | ($play[0] | map(select(.package == $app.package_name))) as $keys
    | .sha1_hashes = append_missing(.sha1_hashes; [$keys[].sha1])
    | .sha256_hashes = append_missing(.sha256_hashes; [$keys[].sha256])
  ) as $apps
  | "# Firebase Android apps under Terraform. Everything here is public: app IDs",
    "# and signing certificate fingerprints. Never put a secret in this file.",
    "#",
    "# Generated by infra/scripts/firebase_android_inventory.sh from the live",
    "# Firebase apps plus the Play app-signing fingerprints. Keep each hash list in",
    "# the order the API returns it and append new fingerprints at the end.",
    "# See docs/infrastructure_as_code.md.",
    "",
    "android_apps = {",
    ($apps[] |
      "  \"\(.environment)-\(.role)\" = {",
      "    project       = \"\(.project)\"",
      "    app_id        = \"\(.app_id)\"",
      "    package_name  = \"\(.package_name)\"",
      "    display_name  = \(.display_name | tojson)",
      "    sha1_hashes   = \(.sha1_hashes | hcl_list)",
      "    sha256_hashes = \(.sha256_hashes | hcl_list)",
      "  }"),
    "}",
    "",
    "allow_fingerprint_removal = false"
' "$work/apps.json"
