import 'package:catch_test_support/repo_file.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('iOS launch marks use generated role-specific geometry', () {
    final consumerLaunch = repoFile(
      'apps/consumer/ios/Runner/Base.lproj/LaunchScreen.storyboard',
    ).readAsStringSync();
    final hostLaunch = repoFile(
      'apps/host/ios/Runner/Base.lproj/LaunchScreen.storyboard',
    ).readAsStringSync();

    expect(
      consumerLaunch,
      contains('Generated by tool/branding/generate_native_brand_assets.dart.'),
    );
    expect(
      consumerLaunch,
      contains(
        'firstAttribute="leading" relation="greaterThanOrEqual" '
        'secondItem="Ze5-6b-2t3" secondAttribute="leading" constant="1"',
      ),
    );
    expect(
      consumerLaunch,
      contains(
        'firstAttribute="centerX" secondItem="Ze5-6b-2t3" '
        'secondAttribute="centerX" constant="-145" priority="750"',
      ),
    );
    expect(
      consumerLaunch,
      contains(
        'firstAttribute="top" relation="greaterThanOrEqual" '
        'secondItem="Ze5-6b-2t3" secondAttribute="top" constant="198"',
      ),
    );
    expect(
      consumerLaunch,
      contains(
        'firstAttribute="top" relation="greaterThanOrEqual" '
        'secondItem="6Tk-OE-BBY" secondAttribute="top" constant="152"',
      ),
    );
    expect(consumerLaunch, contains('firstAttribute="width" constant="138"'));
    expect(consumerLaunch, contains('firstAttribute="height" constant="138"'));
    expect(
      hostLaunch,
      contains('Generated by tool/branding/generate_native_brand_assets.dart.'),
    );
    expect(
      hostLaunch,
      contains(
        'firstAttribute="centerX" secondItem="6Tk-OE-BBY" '
        'secondAttribute="centerX"',
      ),
    );
    expect(
      hostLaunch,
      contains(
        'firstAttribute="top" secondItem="6Tk-OE-BBY" '
        'secondAttribute="top" constant="72"',
      ),
    );
    expect(hostLaunch, contains('firstAttribute="width" constant="224"'));
    expect(hostLaunch, contains('firstAttribute="height" constant="224"'));
    expect(
      hostLaunch,
      isNot(
        contains(
          'firstAttribute="centerY" secondItem="Ze5-6b-2t3" '
          'secondAttribute="centerY"',
        ),
      ),
    );
    expect(hostLaunch, isNot(contains('constant="-145" priority="750"')));
  });
}
