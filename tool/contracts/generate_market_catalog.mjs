#!/usr/bin/env node
// Generates every consumer copy of contracts/catalogs/markets.json, the one
// source of truth for the countries and cities Catch serves, and fails when a
// copy drifts or a hand-maintained city list appears.
//
//   node tool/contracts/generate_market_catalog.mjs          write the copies
//   node tool/contracts/generate_market_catalog.mjs --check  fail on drift
//   node tool/contracts/generate_market_catalog.mjs --prune  lower the allowlist
//   node tool/contracts/generate_market_catalog.mjs --check --without-schema
//     the same check with no installed packages, for the mandatory Node-only
//     lane; contracts:market-catalog adds the schema whenever the catalog,
//     its schema or this generator changes
//
// --check validates the catalog against contracts/shared/
// market_catalog.schema.json and its cross-record rules, compares each
// generated copy, and scans tracked source for lists that name three or more
// catalog cities. Files in market_list_allowlist.json may keep their recorded
// count; the allowlist may only shrink.
import {execFileSync} from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {createFunctionsRequire} from "../lib/repo_paths.mjs";
import {
  canonicalMarketsFromCatalog,
  countryRecordsFromCatalog,
  marketCatalogErrors,
  marketCatalogPath,
  marketCatalogSchemaPath,
  readMarketCatalog,
  repoRoot,
} from "../lib/market_catalog.mjs";

const toolDir = path.dirname(fileURLToPath(import.meta.url));
const allowlistPath = path.join(toolDir, "market_list_allowlist.json");
const generator = "tool/contracts/generate_market_catalog.mjs";

export const outputPaths = Object.freeze({
  functions: "functions/src/shared/generated/marketCatalog.ts",
  dart: "packages/kernel/lib/market_catalog.dart",
  admin: "admin/src/shared/config/generated/marketCatalog.ts",
  website: "website/src/content/markets/generated/catalog.ts",
  rules: "firestore.rules",
});

const tsHeader = [
  `// AUTO-GENERATED by ${generator}`,
  `// Source: ${marketCatalogPath}`,
  "// DO NOT EDIT DIRECTLY.",
].join("\n");

// ---------------------------------------------------------------- validation

export function schemaErrors(catalog, root = repoRoot) {
  const requireFromFunctions = createFunctionsRequire();
  const Ajv = requireFromFunctions("ajv");
  const ajv = new (Ajv.default ?? Ajv)({allErrors: true, strict: false});
  const schema = JSON.parse(
    fs.readFileSync(path.join(root, marketCatalogSchemaPath), "utf8")
  );
  const validate = ajv.compile(schema);
  if (validate(catalog)) return [];
  return validate.errors.map((error) =>
    `${marketCatalogPath}${error.instancePath || "/"}: ${error.message}`
  );
}

// ------------------------------------------------------------------- outputs

export function renderFunctionsModule(catalog) {
  const records = canonicalMarketsFromCatalog(catalog);
  return `${tsHeader}
/* eslint-disable max-len */
import type {CanonicalMarket} from "../../locations/marketConfig";

export const marketCatalogConfigCitiesVersion = ${catalog.configCitiesVersion};

export const canonicalMarketRecords: CanonicalMarket[] = ${JSON.stringify(records, null, 2)};
`;
}

export function renderAdminModule(catalog) {
  const countries = new Map(catalog.countries.map((c) => [c.isoCode, c]));
  const launchMarkets = catalog.cities
    .filter((city) => city.lifecycle === "live")
    .map((city) => ({
      id: city.marketId,
      label: `${city.label} · ${city.regionName}`,
      cityName: city.label,
      regionName: city.regionName,
      countryCode: city.countryIsoCode,
      countryName: countries.get(city.countryIsoCode).name,
      publicPageCitySlug: city.slug,
    }));
  const cities = catalog.cities.map((city) => ({
    marketId: city.marketId,
    cityId: city.cityId,
    slug: city.slug,
    label: city.label,
    regionName: city.regionName,
    countryIsoCode: city.countryIsoCode,
    lifecycle: city.lifecycle,
    websiteListed: city.surfaces.websiteListed,
    aliases: city.aliases,
    legacyIds: city.legacyIds ?? [],
  }));
  return `${tsHeader}

/** Live cities: the markets admin may publish organizers and events into. */
export const generatedLaunchMarkets = ${JSON.stringify(launchMarkets, null, 2)} as const;

/** Every catalog city in display order, with its lifecycle. */
export const generatedMarketCities = ${JSON.stringify(cities, null, 2)} as const;

/** Countries Catch serves. */
export const generatedMarketCountries = ${JSON.stringify(countryRecordsFromCatalog(catalog), null, 2)} as const;
`;
}

const titleCase = (slug) => slug.split("-")
  .map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(" ");

/**
 * Cities the public website lists (websiteListed), in catalog order. Aliases
 * are the human spellings listings use ("New Delhi", "Bangalore");
 * legacySlugs are the website's retired path slugs, which redirect.
 */
export function websiteCitiesFromCatalog(catalog) {
  return catalog.cities.filter((city) => city.surfaces.websiteListed)
    .map((city) => {
      const aliases = Array.from(new Set([city.cityLabel, ...city.aliases.map(titleCase)]))
        .filter((alias) => alias.toLowerCase() !== city.label.toLowerCase());
      const legacySlugs = (city.legacyIds ?? [])
        .map((id) => id.replace(/^[a-z]{2}-/u, ""))
        .filter((slug) => slug !== city.slug);
      return {
        id: city.marketId,
        slug: city.slug,
        marketSlug: city.slug,
        label: city.label,
        aliases,
        legacySlugs,
        timezone: city.timeZone,
        status: city.lifecycle,
        ...(city.launchDate === undefined ? {} : {launchDate: city.launchDate}),
        countryIsoCode: city.countryIsoCode,
        latitude: city.latitude,
        longitude: city.longitude,
      };
    });
}

