const dartString = (value) =>
  `'${value.replace(/\\/gu, "\\\\").replace(/'/gu, "\\'").replace(/\$/gu, "\\$")}'`;
const dartDouble = (value) =>
  Number.isInteger(value) ? `${value}.0` : String(value);

// Matches dart format: an argument over 80 columns splits its list.
function dartListArgument(name, values, indent) {
  const items = values.map(dartString);
  const line = `${indent}${name}: [${items.join(", ")}],`;
  if (line.length <= 80) return line;
  return [
    `${indent}${name}: [`,
    ...items.map((item) => `${indent}  ${item},`),
    `${indent}],`,
  ].join("\n");
}

function dartArgument(name, value, indent) {
  const line = `${indent}${name}: ${value},`;
  if (line.length <= 80) return line;
  return `${indent}${name}:\n${indent}    ${value},`;
}

export function renderDartModule(catalog) {
  const countries = new Map(catalog.countries.map((c) => [c.isoCode, c]));
  const slugByMarketId = new Map(catalog.cities.map((c) => [c.marketId, c.slug]));
  const records = canonicalMarketsFromCatalog(catalog);
  const cityOptions = records.map((record) => {
    const lines = [
      dartArgument("name", dartString(record.slug), "    "),
      dartArgument("cityId", dartString(record.cityId), "    "),
      dartArgument("marketId", dartString(record.marketId), "    "),
      dartArgument("slug", dartString(record.slug), "    "),
      dartArgument("label", dartString(record.label), "    "),
      dartArgument("latitude", dartDouble(record.latitude), "    "),
      dartArgument("longitude", dartDouble(record.longitude), "    "),
      dartArgument("countryIsoCode", dartString(record.countryIsoCode), "    "),
      dartArgument("currencyCode", dartString(record.currencyCode), "    "),
      dartArgument("dialCode", dartString(record.dialCode), "    "),
      dartArgument("timeZone", dartString(record.timeZone), "    "),
      // CityOption defaults: launchStatus 'planned', lifecycle 'hidden', flags
      // false, no launch date, no aliases.
      ...(record.launchStatus === "planned" ? [] :
        [dartArgument("launchStatus", dartString(record.launchStatus), "    ")]),
      ...["profileSelectable", "hostCreatable", "eventCreatable",
        "exploreVisible"].filter((flag) => record[flag])
        .map((flag) => dartArgument(flag, "true", "    ")),
      ...(record.lifecycle === "hidden" ? [] :
        [dartArgument("lifecycle", dartString(record.lifecycle), "    ")]),
      ...(record.websiteListed ? [dartArgument("websiteListed", "true", "    ")] : []),
      ...(record.launchDate === undefined ? [] :
        [dartArgument("launchDate", dartString(record.launchDate), "    ")]),
      ...(record.aliases.length === 0 ? [] :
        [dartListArgument("aliases", record.aliases, "    ")]),
    ];
    return `  CityOption(\n${lines.join("\n")}\n  ),`;
  });
  const countryMarket = (country) => {
    const lines = [
      dartArgument("isoCode", dartString(country.isoCode), "  "),
      dartArgument("label", dartString(country.name), "  "),
      dartArgument("dialCode", dartString(country.dialCode), "  "),
      dartArgument("currencyCode", dartString(country.currencyCode), "  "),
      dartArgument("currencySymbol", dartString(country.currencySymbol), "  "),
      dartArgument(
        "defaultCityName",
        dartString(slugByMarketId.get(country.defaultMarketId)),
        "  "
      ),
      dartArgument("timeZone", dartString(country.timeZone), "  "),
    ];
    return `CountryMarket(\n${lines.join("\n")}\n)`;
  };
  const defaultCountry = countries.get(catalog.defaultCountryIsoCode);
  const otherCountries = catalog.countries
    .filter((country) => country.isoCode !== defaultCountry.isoCode)
    .map((country) => `  ${countryMarket(country).replaceAll("\n", "\n  ")},`);
  const favorites = dartListArgument(
    "x",
    catalog.countries.map((country) => country.isoCode),
    ""
  ).replace(/^x: /u, "").replace(/,$/u, "");
  return `// copy:allow-file(Generated geographic proper-noun market catalog)
${tsHeader}
import 'package:catch_kernel/city_catalog.dart';
import 'package:catch_kernel/country_markets.dart';

const generatedDefaultCountryIsoCode = ${dartString(defaultCountry.isoCode)};
const generatedDefaultCountryDialCode = ${dartString(defaultCountry.dialCode)};
const generatedDefaultCurrencyCode = ${dartString(defaultCountry.currencyCode)};
const generatedDefaultTimeZone = ${dartString(defaultCountry.timeZone)};

const generatedCountryPickerFavorites = ${favorites};

const generatedDefaultCountryMarket = ${countryMarket(defaultCountry)};

const generatedCountryMarkets = [
  generatedDefaultCountryMarket,
${otherCountries.join("\n")}
];

const generatedCityOptions = [
${cityOptions.join("\n")}
];
`;
}

const rulesBegin =
  `    // BEGIN GENERATED launch markets (${generator})`;
const rulesEnd = "    // END GENERATED launch markets";

export function renderRules(catalog, currentRules) {
  const launched = canonicalMarketsFromCatalog(catalog)
    .filter((record) => record.launchStatus === "launched")
    .map((record) => `        '${record.marketId}'`);
  const block = [
    rulesBegin,
    "    function isDefaultCity(city) {",
    "      return city in [",
    launched.join(",\n"),
    "      ];",
    "    }",
    rulesEnd,
  ].join("\n");
  const start = currentRules.indexOf(rulesBegin);
  const end = currentRules.indexOf(rulesEnd);
  if (start < 0 || end < start) {
    throw new Error(
      `${outputPaths.rules} needs the generated launch-market markers.`
    );
  }
  return currentRules.slice(0, start) + block +
    currentRules.slice(end + rulesEnd.length);
}

export function outputs(catalog, root = repoRoot) {
  const rules = fs.readFileSync(path.join(root, outputPaths.rules), "utf8");
  return [
    {path: outputPaths.functions, content: renderFunctionsModule(catalog)},
    {path: outputPaths.dart, content: renderDartModule(catalog)},
    {path: outputPaths.admin, content: renderAdminModule(catalog)},
    {path: outputPaths.website, content: renderWebsiteModule(catalog)},
    {path: outputPaths.rules, content: renderRules(catalog, rules)},
  ];
}

// --------------------------------------------------------- reserved slugs

// City pages live at /{slug}/, so no city slug, alias or legacy id may take a
// path the website already routes (/cities/, /explore/, /host/...).
const routeRegistryPath = "website/src/app/routeRegistry.ts";
const systemPrefixes = ["api", "og", "maps", "assets", "fonts", "_next", "_legacy", "private-shell"];

export function reservedWebsiteSlugs(root = repoRoot) {
  const registry = fs.readFileSync(path.join(root, routeRegistryPath), "utf8");
  const routed = [...registry.matchAll(/path: "\/([a-z0-9_-]+)/gu)].map((match) => match[1]);
  return new Set([...routed, ...systemPrefixes]);
}

export function reservedSlugErrors(catalog, reserved = reservedWebsiteSlugs()) {
  return catalog.cities.flatMap((city) =>
    [city.slug, ...city.aliases, ...(city.legacyIds ?? [])]
      .filter((key) => reserved.has(key))
      .map((key) => `${city.marketId}: "${key}" is a website path (${routeRegistryPath}).`)
  );
}

// ------------------------------------------------------ catalog references

// A "reference" allowlist entry selects catalog cities by slug (crawl targets,
// search matrices) instead of copying the catalog. Its validatedBy names the
// test, owned beside the file, that checks every reference against
// contracts/catalogs/markets.json; that test must read the catalog.
export function referenceEntryErrors(file, entry, root = repoRoot) {
  const test = entry.validatedBy;
  if (typeof test !== "string" || !/\.test\.m?js$/u.test(test)) {
    return [`${file}: a reference entry needs validatedBy, the test that checks it.`];
  }
  const absolute = path.join(root, test);
  if (!fs.existsSync(absolute)) {
    return [`${file}: validatedBy ${test} does not exist.`];
  }
  const text = fs.readFileSync(absolute, "utf8");
  if (!text.includes("contracts/catalogs/markets.json")) {
    return [`${file}: validatedBy ${test} does not read ${marketCatalogPath}.`];
  }
  return [];
}

// ------------------------------------------------- hand-maintained list scan

export const handListThreshold = 3;

// Never scanned: the catalog and its schema, generated copies, prose, tests,
// fixtures and stories (which may name any city), and vendored design packs.
const excluded = [
  /^contracts\/catalogs\/markets\.json$/u,
  /^contracts\/shared\/market_catalog\.schema\.json$/u,
  /^contracts\/fixtures\//u,
  /^tool\/contracts\/market_list_allowlist\.json$/u,
  /^docs\//u,
  /^design\//u,
  /\.md$/u,
  /(^|\/)(test|tests|__tests__|fixtures|integration_test|design_fixtures)\//u,
  /(\.test\.|\.spec\.|\.stories\.|_test\.dart$)/u,
];
const scanned = /\.(?:m?[jt]sx?|cjs|dart|json|rules|ya?ml)$/u;
const quoted = /["'`]([A-Za-z][A-Za-z .-]{2,30})["'`]/gu;

export function cityTokens(catalog) {
  const tokens = new Map();
  for (const city of catalog.cities) {
    for (const token of [
      city.marketId,
      city.cityId,
      city.slug,
      city.label,
      city.cityLabel,
      ...city.aliases,
      ...(city.legacyIds ?? []),
    ]) {
      if (token.length >= 3) tokens.set(token.toLowerCase(), city.marketId);
    }
  }
  return tokens;
}

/** Distinct catalog cities a file names in string literals. */
export function citiesNamed(text, tokens) {
  const found = new Set();
  for (const match of text.matchAll(quoted)) {
    const marketId = tokens.get(match[1].toLowerCase());
    if (marketId) found.add(marketId);
  }
  return found.size;
}

export function trackedSourceFiles(root = repoRoot) {
  const generated = new Set(Object.values(outputPaths));
  return execFileSync("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  }).split("\0").filter((file) => file && scanned.test(file) &&
    !generated.has(file) && !excluded.some((pattern) => pattern.test(file)));
}

export function scanHandLists(catalog, root = repoRoot,
  files = trackedSourceFiles(root)) {
  const tokens = cityTokens(catalog);
  const found = {};
  for (const file of files) {
    const absolute = path.join(root, file);
    if (!fs.existsSync(absolute) || !fs.lstatSync(absolute).isFile()) continue;
    const count = citiesNamed(fs.readFileSync(absolute, "utf8"), tokens);
    if (count >= handListThreshold) found[file] = count;
  }
  return found;
}

export function compareHandLists(found, allowlist, root = repoRoot) {
  const errors = [];
  const stale = [];
  for (const [file, entry] of Object.entries(allowlist)) {
    if (!["pending", "fixture", "reference"].includes(entry.kind) ||
      typeof entry.reason !== "string" || entry.reason.length < 12 ||
      !Number.isInteger(entry.cities)) {
      errors.push(
        `${file}: allowlist entries need cities, kind (pending, fixture or ` +
        "reference) and a reason."
      );
    } else if (entry.kind === "reference") {
      errors.push(...referenceEntryErrors(file, entry, root));
    }
  }
  for (const [file, count] of Object.entries(found)) {
    const limit = allowlist[file]?.cities ?? 0;
    if (count > limit) {
      errors.push(
        `${file}: names ${count} catalog cities (${limit} allowed). Read ` +
        `cities from ${marketCatalogPath} or a generated copy instead of ` +
        "keeping a hand-maintained list."
      );
    }
  }
  for (const [file, entry] of Object.entries(allowlist)) {
    if ((found[file] ?? 0) < entry.cities) {
      stale.push({file, count: found[file] ?? 0});
    }
  }
  return {errors, stale};
}

// ---------------------------------------------------------------------- main

function readAllowlist() {
  return JSON.parse(fs.readFileSync(allowlistPath, "utf8"));
}

function main() {
  const check = process.argv.includes("--check");
  const prune = process.argv.includes("--prune");
  const withoutSchema = process.argv.includes("--without-schema");
  const catalog = readMarketCatalog();
  const errors = [
    ...(withoutSchema ? [] : schemaErrors(catalog)),
    ...marketCatalogErrors(catalog),
    ...reservedSlugErrors(catalog),
  ];
  if (errors.length > 0) {
    console.error(errors.join("\n"));
    process.exit(1);
  }

  const stale = [];
  for (const output of outputs(catalog)) {
    const target = path.join(repoRoot, output.path);
    const current = fs.existsSync(target) ?
      fs.readFileSync(target, "utf8") : null;
    if (current === output.content) continue;
    if (check) {
      stale.push(output.path);
    } else {
      fs.mkdirSync(path.dirname(target), {recursive: true});
      fs.writeFileSync(target, output.content);
    }
  }
  if (stale.length > 0) {
    console.error(
      `Stale market catalog outputs:\n${stale.join("\n")}\n` +
      `Run: node ${generator}`
    );
    process.exit(1);
  }

  const {allowlisted, ...allowlist} = readAllowlist();
  const result = compareHandLists(scanHandLists(catalog), allowlisted);
  if (result.errors.length > 0) {
    console.error(result.errors.join("\n"));
    process.exit(1);
  }
  if (result.stale.length > 0 && !prune) {
    console.error(
      result.stale.map(({file, count}) =>
        `${file}: allowlist is above the ${count} catalog cities it names.`
      ).join("\n") + `\nRun: node ${generator} --prune`
    );
    process.exit(1);
  }
  if (result.stale.length > 0) {
    for (const {file, count} of result.stale) {
      if (count < handListThreshold) delete allowlisted[file];
      else allowlisted[file].cities = count;
    }
    fs.writeFileSync(
      allowlistPath,
      `${JSON.stringify({...allowlist, allowlisted}, null, 2)}\n`
    );
    console.log(`Lowered ${result.stale.length} allowlist entries.`);
    return;
  }
  console.log(
    check ?
      "Market catalog outputs are current; no unlisted city lists." :
      "Generated market catalog outputs."
  );
}

if (process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
