import 'dart:convert';
import 'dart:io';

const _tokenPath = 'design/tokens/catch.tokens.json';
const _defaultWebsiteCssPath = 'packages/web-config/generated/catch-tokens.css';
const _defaultDartTokensPath =
    'packages/catch_tokens/lib/generated/catch_design_tokens.g.dart';

Future<void> main(List<String> args) async {
  if (args.contains('--help') || args.contains('-h')) {
    _printHelp();
    return;
  }

  final check = args.contains('--check');
  final tokenFile = File(_tokenPath);
  if (!tokenFile.existsSync()) {
    stderr.writeln('Missing token file: $_tokenPath');
    exitCode = 1;
    return;
  }

  final document = jsonDecode(tokenFile.readAsStringSync());
  if (document is! Map<String, dynamic>) {
    stderr.writeln('Token file root must be a JSON object.');
    exitCode = 1;
    return;
  }

  final tokens = _TokenRegistry.fromDocument(document);
  final catchExtension = _catchExtension(document);
  final websiteExtension = _mapValue(catchExtension['website'], 'website');
  final dartExtension = _mapValue(catchExtension['dart'], 'dart');
  final websiteOutputPath =
      websiteExtension['output'] as String? ?? _defaultWebsiteCssPath;
  final dartOutputPath =
      dartExtension['output'] as String? ?? _defaultDartTokensPath;
  final css = _buildWebsiteCss(
    registry: tokens,
    websiteExtension: websiteExtension,
  );
  final dart = await _formatDart(_buildDartTokens(tokens), dartOutputPath);

  final failures = <String>[];
  final websiteOutputFile = File(websiteOutputPath);
  final dartOutputFile = File(dartOutputPath);

  if (check) {
    if (!websiteOutputFile.existsSync()) {
      failures.add('missing $websiteOutputPath');
    } else if (websiteOutputFile.readAsStringSync() != css) {
      failures.add('stale $websiteOutputPath');
    }
    if (!dartOutputFile.existsSync()) {
      failures.add('missing $dartOutputPath');
    } else if (dartOutputFile.readAsStringSync() != dart) {
      failures.add('stale $dartOutputPath');
    }
    failures.addAll(_fontAssetFailures(websiteExtension));

    if (failures.isNotEmpty) {
      stderr.writeln('Design token check failed:');
      for (final failure in failures) {
        stderr.writeln('- $failure');
      }
      stderr.writeln('Run: dart run tool/design_tokens.dart');
      exitCode = 1;
      return;
    }

    stdout.writeln('Design token check passed.');
    return;
  }

  _writeFile(websiteOutputFile, css);
  _writeFile(dartOutputFile, dart);
  _syncFontAssets(websiteExtension);
  stdout.writeln(
    'Generated $websiteOutputPath and $dartOutputPath from $_tokenPath.',
  );
}

String _buildWebsiteCss({
  required _TokenRegistry registry,
  required Map<String, dynamic> websiteExtension,
}) {
  final buffer = StringBuffer()
    ..writeln('/*')
    ..writeln(' * Generated by `dart run tool/design_tokens.dart`.')
    ..writeln(' * Source: $_tokenPath')
    ..writeln(' * Do not edit by hand.')
    ..writeln(' */')
    ..writeln();

  for (final fontFace in _fontFaces(websiteExtension)) {
    buffer
      ..writeln('@font-face {')
      ..writeln('  font-family: "${fontFace.family}";')
      ..writeln('  src: url("${fontFace.url}") format("${fontFace.format}");')
      ..writeln('  font-weight: ${fontFace.weight};')
      ..writeln('  font-style: ${fontFace.style};')
      ..writeln('  font-display: swap;')
      ..writeln('}')
      ..writeln();
  }

  buffer.writeln(':root {');

  for (final token in registry.tokens.values) {
    // Pinned native research is input to semantic decisions, not a second
    // public stylesheet/API that feature code can use to bypass those decisions.
    if (token.path.first == 'platformReference') continue;
    final cssName = _cssVariableName(token.path);
    final cssValue = registry.cssValue(token);
    if (cssValue == null) continue;
    buffer.writeln('  $cssName: $cssValue;');
  }

  for (final token in registry.tokens.values.where(_isActivityColorToken)) {
    final swatches = _derivedActivitySwatches(
      _mapValue(registry.resolvedValue(token), token.referencePath),
    );
    for (final entry in swatches.entries) {
      buffer.writeln(
        '  --catch-activity-${_kebab(token.path[1])}-${entry.key}: ${entry.value};',
      );
    }
  }

  final aliases = _mapValue(websiteExtension['legacyAliases'], 'legacyAliases');
  if (aliases.isNotEmpty) {
    buffer.writeln();
    buffer.writeln(
      '  /* Temporary compatibility aliases for website/styles.css. */',
    );
    for (final entry in aliases.entries) {
      final name = entry.key;
      final value = entry.value;
      final cssValue = registry.cssValueFromExtensionValue(value);
      buffer.writeln('  --$name: $cssValue;');
    }
  }

  buffer.writeln('}');
  _writeThemeRoles(buffer, registry);

  return buffer.toString();
}

/// Theme roles let a component read one colour name in either theme. Light is
/// the default; a subtree opts into dark with `data-catch-theme="dark"`.
void _writeThemeRoles(StringBuffer buffer, _TokenRegistry registry) {
  List<String> roles(String mode, String group) => [
    for (final token in registry.tokens.values)
      if (token.path.length == 4 &&
          token.path[0] == 'theme' &&
          token.path[1] == mode &&
          token.path[2] == group)
        token.path[3],
  ];
  // Colours resolve to --catch-theme-<role>; themed shadows resolve to the
  // same --catch-elevation-<role> name in both themes.
  final groups = {'color': '--catch-theme-', 'elevation': '--catch-elevation-'};
  for (final group in groups.keys) {
    final light = roles('light', group);
    final dark = roles('dark', group);
    if ((group == 'color' && light.isEmpty) ||
        light.length != dark.length ||
        !light.toSet().containsAll(dark)) {
      throw FormatException('Light and dark $group roles must match.');
    }
  }
  for (final (selector, mode) in [
    (':root,\n[data-catch-theme="light"]', 'light'),
    ('[data-catch-theme="dark"]', 'dark'),
  ]) {
    buffer
      ..writeln()
      ..writeln('$selector {');
    for (final MapEntry(key: group, value: prefix) in groups.entries) {
      for (final role in roles('light', group)) {
        buffer.writeln(
          '  $prefix${_kebab(role)}: '
          'var(${_cssVariableName(['theme', mode, group, role])});',
        );
      }
    }
    buffer.writeln('}');
  }
}

String _buildDartTokens(_TokenRegistry registry) {
  final buffer = StringBuffer()
    ..writeln('// Generated by `dart run tool/design_tokens.dart`.')
    ..writeln('// Source: $_tokenPath')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln()
    ..writeln('abstract final class GeneratedCatchColorTokens {');

  for (final token in registry.tokens.values.where(_isThemeColorToken)) {
    buffer.writeln(
      '  static const Color ${_dartThemeTokenName(token)} = '
      '${_dartColorValue(registry.resolvedValue(token))};',
    );
  }

  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchGradientTokens {');

  for (final token in registry.tokens.values.where(_isThemeGradientToken)) {
    buffer.writeln(
      '  static const Gradient ${_dartThemeTokenName(token)} = '
      '${_dartGradientValue(registry, token)};',
    );
  }

  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchSpacingTokens {');

  for (final token in registry.tokens.values.where(_isSpacingToken)) {
    buffer.writeln(
      '  static const double ${token.path.last} = '
      '${_dartDimensionNumber(registry.resolvedValue(token))};',
    );
  }

  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchRadiusTokens {');

  for (final token in registry.tokens.values.where(_isRadiusToken)) {
    buffer.writeln(
      '  static const double ${token.path.last} = '
      '${_dartDimensionNumber(registry.resolvedValue(token))};',
    );
  }

  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchFontFamilyTokens {');

  for (final token in registry.tokens.values.where(_isFontFamilyToken)) {
    buffer.writeln(
      '  static const String ${token.path.last} = '
      '${_dartStringLiteral(registry.resolvedValue(token).toString())};',
    );
  }

  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchActivityPigmentTokens {');

  for (final token in registry.tokens.values.where(_isActivityColorToken)) {
    buffer.writeln(
      '  static const Color ${token.path[1]} = '
      '${_dartColorValue(registry.resolvedValue(token))};',
    );
  }

  buffer.writeln('}');
  _writeColorGroup(buffer, registry, 'palette', 'GeneratedCatchPaletteTokens');
  _writeColorGroup(buffer, registry, 'ground', 'GeneratedCatchGroundTokens');
  _writeColorGroup(buffer, registry, 'format', 'GeneratedCatchFormatTokens');
  buffer
    ..writeln()
    ..writeln('abstract final class GeneratedCatchWebsiteTokens {');

  for (final token in registry.tokens.values.where(_isWebsiteToken)) {
    buffer.writeln(
      '  static const double ${_camel(token.path.skip(1))} = '
      '${_dartDimensionNumber(registry.resolvedValue(token))};',
    );
  }

  buffer.writeln('}');
  _writePlatformTokens(buffer, registry);

  return buffer.toString();
}

/// The pre-commit hook runs `dart format` on staged Dart files, so emit the
/// formatter's output; otherwise committing the file would make `--check` fail.
Future<String> _formatDart(String source, String outputPath) async {
  final process = await Process.start(Platform.resolvedExecutable, [
    'format',
    '--output=show',
    '--stdin-name=$outputPath',
  ]);
  final formatted = process.stdout.transform(utf8.decoder).join();
  final errors = process.stderr.transform(utf8.decoder).join();
  process.stdin.write(source);
  await process.stdin.close();
  if (await process.exitCode != 0) {
    throw StateError('dart format failed for $outputPath: ${await errors}');
  }
  return formatted;
}

Map<String, dynamic> _catchExtension(Map<String, dynamic> document) {
  final extensions = _mapValue(document[r'$extensions'], r'$extensions');
  return _mapValue(extensions['org.catch'], 'org.catch');
}

List<_FontFace> _fontFaces(Map<String, dynamic> websiteExtension) {
  final rawFontFaces = websiteExtension['fontFaces'];
  if (rawFontFaces == null) return const <_FontFace>[];
  if (rawFontFaces is! List<dynamic>) {
    throw const FormatException('website.fontFaces must be an array.');
  }
  return rawFontFaces
      .map((value) => _FontFace.fromJson(_mapValue(value, 'fontFace')))
      .toList(growable: false);
}

void _syncFontAssets(Map<String, dynamic> websiteExtension) {
  for (final fontFace in _fontFaces(websiteExtension)) {
    final source = File(fontFace.source);
    if (!source.existsSync()) {
      throw StateError('Missing font source: ${fontFace.source}');
    }
    final target = File(fontFace.target);
    target.parent.createSync(recursive: true);
    target.writeAsBytesSync(source.readAsBytesSync());
  }
}

List<String> _fontAssetFailures(Map<String, dynamic> websiteExtension) {
  final failures = <String>[];
  for (final fontFace in _fontFaces(websiteExtension)) {
    final source = File(fontFace.source);
    final target = File(fontFace.target);
    if (!source.existsSync()) {
      failures.add('missing ${fontFace.source}');
      continue;
    }
    if (!target.existsSync()) {
      failures.add('missing ${fontFace.target}');
      continue;
    }
    final sourceBytes = source.readAsBytesSync();
    final targetBytes = target.readAsBytesSync();
    if (!_sameBytes(sourceBytes, targetBytes)) {
      failures.add('stale ${fontFace.target}');
    }
  }
  return failures;
}

bool _sameBytes(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i += 1) {
    if (a[i] != b[i]) return false;
  }
  return true;
}

void _writeFile(File file, String contents) {
  file.parent.createSync(recursive: true);
  file.writeAsStringSync(contents);
}

Map<String, dynamic> _mapValue(Object? value, String label) {
  if (value == null) return <String, dynamic>{};
  if (value is Map<String, dynamic>) return value;
  if (value is Map) {
    return value.map((key, value) => MapEntry(key.toString(), value));
  }
  throw FormatException('$label must be an object.');
}

String _cssVariableName(List<String> path) {
  if (path.length == 4 && path[0] == 'theme' && path[2] == 'color') {
    return '--catch-color-${_kebab(path[1])}-${_kebab(path[3])}';
  }
  if (path.length == 3 && path[0] == 'font' && path[1] == 'family') {
    return '--catch-font-${_kebab(path[2])}';
  }
  return '--catch-${path.map(_kebab).join('-')}';
}

bool _isThemeColorToken(_Token token) =>
    token.path.length == 4 &&
    token.path[0] == 'theme' &&
    token.path[2] == 'color' &&
    token.type == 'color';

bool _isThemeGradientToken(_Token token) =>
    token.path.length == 4 &&
    token.path[0] == 'theme' &&
    token.path[2] == 'gradient' &&
    token.type == 'gradient';

bool _isSpacingToken(_Token token) =>
    token.path.length == 2 && token.path[0] == 'space';

bool _isRadiusToken(_Token token) =>
    token.path.length == 2 && token.path[0] == 'radius';

bool _isFontFamilyToken(_Token token) =>
    token.path.length == 3 &&
    token.path[0] == 'font' &&
    token.path[1] == 'family';

bool _isActivityColorToken(_Token token) =>
    token.path.length == 3 &&
    token.path[0] == 'activity' &&
    token.path[2] == 'accent' &&
    token.type == 'color';

bool _isWebsiteToken(_Token token) =>
    token.path.length == 3 &&
    token.path[0] == 'website' &&
    token.type == 'dimension';

String _dartThemeTokenName(_Token token) =>
    '${token.path[1]}${_pascal(token.path[3])}';

String _dartColorValue(Object? value) {
  final color = _mapValue(value, 'color value');
  final components = color['components'];
  if (color['colorSpace'] != 'srgb') {
    throw const FormatException(
      'Only srgb color tokens can be emitted to Dart.',
    );
  }
  if (components is! List || components.length != 3) {
    throw const FormatException('srgb color components must have 3 values.');
  }

  final red = _componentToByte(components[0]);
  final green = _componentToByte(components[1]);
  final blue = _componentToByte(components[2]);
  final alpha = color['alpha'] as num? ?? 1;
  if (alpha == 1) {
    final hex = color['hex'];
    if (hex is String) return 'Color(0xFF${hex.substring(1).toUpperCase()})';
    return 'Color(0xFF${_hexByte(red)}${_hexByte(green)}${_hexByte(blue)})';
  }
  return 'Color.fromRGBO($red, $green, $blue, ${_formatDartNumber(alpha)})';
}

String _dartGradientValue(_TokenRegistry registry, _Token token) {
  final value = _mapValue(registry.resolvedValue(token), 'gradient value');
  final type = value['type'];
  if (type != 'linear') {
    throw FormatException('Unsupported gradient type: $type.');
  }

  final begin = _mapValue(value['begin'], 'gradient begin');
  final end = _mapValue(value['end'], 'gradient end');
  final colors = value['colors'];
  if (colors is! List || colors.isEmpty) {
    throw const FormatException('gradient colors must be a non-empty array.');
  }

  final colorValues = colors
      .map((color) => _dartColorValue(_gradientColorValue(registry, color)))
      .join(', ');
  return 'LinearGradient('
      'begin: ${_dartAlignment(begin)}, '
      'end: ${_dartAlignment(end)}, '
      'colors: <Color>[$colorValues],'
      ')';
}

Object? _gradientColorValue(_TokenRegistry registry, Object? value) {
  if (value is String && _isReference(value)) {
    return registry.resolvedValue(registry.tokenForReference(value));
  }
  if (value is String && value.startsWith('#')) {
    return _hexColorValue(value);
  }
  return value;
}

Map<String, Object> _hexColorValue(String hex) {
  final normalized = hex.startsWith('#') ? hex.substring(1) : hex;
  if (normalized.length != 6) {
    throw FormatException('Expected #RRGGBB color, got $hex.');
  }
  final red = int.parse(normalized.substring(0, 2), radix: 16) / 255;
  final green = int.parse(normalized.substring(2, 4), radix: 16) / 255;
  final blue = int.parse(normalized.substring(4, 6), radix: 16) / 255;
  return <String, Object>{
    'colorSpace': 'srgb',
    'components': <num>[red, green, blue],
    'hex': '#${normalized.toUpperCase()}',
  };
}

String _dartDimensionNumber(Object? value) {
  final dimension = _mapValue(value, 'dimension value');
  if (dimension['unit'] != 'px') {
    throw const FormatException('Only px dimensions can be emitted to Dart.');
  }
  final number = dimension['value'];
  if (number is! num) {
    throw const FormatException('dimension value must be numeric.');
  }
  return _formatDartNumber(number);
}

num _requiredNumber(Map<String, dynamic> value, String key) {
  final number = value[key];
  if (number is! num) {
    throw FormatException('$key must be numeric.');
  }
  return number;
}

String _dartAlignment(Map<String, dynamic> value) {
  final x = _requiredNumber(value, 'x');
  final y = _requiredNumber(value, 'y');
  if (x == -1 && y == -1) return 'Alignment.topLeft';
  if (x == 1 && y == 1) return 'Alignment.bottomRight';
  if (x == 0 && y == 0) return 'Alignment.center';
  return 'Alignment(${_formatDartNumber(x)}, ${_formatDartNumber(y)})';
}

String _hexByte(int value) =>
    value.toRadixString(16).padLeft(2, '0').toUpperCase();

String _dartStringLiteral(String value) => "'${value.replaceAll("'", r"\'")}'";

String _formatDartNumber(num value) {
  if (value == value.roundToDouble()) return '${value.toInt()}.0';
  return value.toString();
}

String _pascal(String input) {
  final parts = input.split(RegExp(r'[-_]'));
  return parts.map((part) {
    if (part.isEmpty) return part;
    return part[0].toUpperCase() + part.substring(1);
  }).join();
}

String _camel(Iterable<String> parts) {
  final list = parts.toList(growable: false);
  if (list.isEmpty) return '';
  return list.first + list.skip(1).map(_pascal).join();
}

String _kebab(String input) {
  final buffer = StringBuffer();
  for (var i = 0; i < input.length; i += 1) {
    final char = input[i];
    final isUpper = char.toUpperCase() == char && char.toLowerCase() != char;
    if (isUpper && i > 0) buffer.write('-');
    buffer.write(char.toLowerCase() == '_' ? '-' : char.toLowerCase());
  }
  return buffer.toString();
}

void _printHelp() {
  stdout.writeln('''
Usage: dart run tool/design_tokens.dart [--check]

Generates website token CSS, website font assets, and Flutter Dart constants
from $_tokenPath.

Options:
  --check   Rebuild in memory and fail if generated outputs are stale.
''');
}

final class _TokenRegistry {
  _TokenRegistry._(this.tokens);

  final Map<String, _Token> tokens;

  factory _TokenRegistry.fromDocument(Map<String, dynamic> document) {
    final tokens = <String, _Token>{};

    void walk(Object? node, List<String> path, String? inheritedType) {
      if (node is! Map) return;
      final map = _mapValue(node, path.join('.'));
      final type = map[r'$type'] as String? ?? inheritedType;

      if (map.containsKey(r'$value')) {
        if (path.isEmpty) {
          throw const FormatException('Root token is not supported.');
        }
        final token = _Token(
          path: List<String>.unmodifiable(path),
          type: type,
          value: map[r'$value'],
        );
        tokens[token.referencePath] = token;
      }

      for (final entry in map.entries) {
        if (entry.key.startsWith(r'$')) continue;
        walk(entry.value, [...path, entry.key], type);
      }
    }

    walk(document, const <String>[], null);
    return _TokenRegistry._(tokens);
  }

  String? cssValue(_Token token) {
    final value = _resolveValue(token.value);
    return _cssValueForType(token.type, value);
  }

  Object? resolvedValue(_Token token) => _resolveValue(token.value);

  String cssValueFromExtensionValue(Object? value) {
    if (value is String && _isReference(value)) {
      final token = tokenForReference(value);
      return 'var(${_cssVariableName(token.path)})';
    }
    return _rawCssValue(value);
  }

  Object? _resolveValue(Object? value, [Set<String>? visited]) {
    if (value is String && _isReference(value)) {
      final path = _referencePath(value);
      final chain = visited ?? <String>{};
      if (!chain.add(path)) {
        throw FormatException('Cyclic token reference: $path');
      }
      return _resolveValue(tokenForReference(value).value, chain);
    }
    return value;
  }

  _Token tokenForReference(String reference) {
    final path = _referencePath(reference);
    final token = tokens[path];
    if (token == null) {
      throw FormatException('Unknown token reference: $reference');
    }
    return token;
  }

  String? _cssValueForType(String? type, Object? value) {
    switch (type) {
      case 'color':
        return _colorCssValue(_mapValue(value, 'color value'));
      case 'dimension':
        return _dimensionCssValue(_mapValue(value, 'dimension value'));
      case 'number':
        return _rawCssValue(value);
      case 'fontFamily':
        return '"$value"';
      case 'duration':
        return _dimensionCssValue(_mapValue(value, 'duration value'));
      case 'cubicBezier':
        if (value is! List ||
            value.length != 4 ||
            value.any((v) => v is! num)) {
          throw const FormatException('cubicBezier needs four numeric values.');
        }
        return 'cubic-bezier(${value.map((v) => _formatNumber(v as num)).join(', ')})';
      case 'shadow':
        return _shadowLayers(value)
            .map(
              (layer) =>
                  '${_cssLength(layer.x)} ${_cssLength(layer.y)} '
                  '${_cssLength(layer.blur)}'
                  '${layer.spread == 0 ? '' : ' ${_cssLength(layer.spread)}'} '
                  '${_colorCssValue(layer.color)}',
            )
            .join(', ');
      default:
        if (value is String || value is num) return _rawCssValue(value);
        return null;
    }
  }
}

final class _Token {
  const _Token({required this.path, required this.type, required this.value});

  final List<String> path;
  final String? type;
  final Object? value;

  String get referencePath => path.join('.');
}

final class _FontFace {
  const _FontFace({
    required this.family,
    required this.style,
    required this.weight,
    required this.source,
    required this.target,
    required this.url,
    required this.format,
  });

  factory _FontFace.fromJson(Map<String, dynamic> json) {
    String requiredString(String key) {
      final value = json[key];
      if (value is! String || value.isEmpty) {
        throw FormatException('fontFace.$key must be a non-empty string.');
      }
      return value;
    }

    return _FontFace(
      family: requiredString('family'),
      style: requiredString('style'),
      weight: requiredString('weight'),
      source: requiredString('source'),
      target: requiredString('target'),
      url:
          json['url'] as String? ??
          '/${requiredString('target').replaceFirst('website/', '')}',
      format: requiredString('format'),
    );
  }

  final String family;
  final String style;
  final String weight;
  final String source;
  final String target;
  final String url;
  final String format;
}

String _colorCssValue(Map<String, dynamic> value) {
  final colorSpace = value['colorSpace'];
  final components = value['components'];
  final alpha = value['alpha'] as num? ?? 1;
  final hex = value['hex'];

  if (colorSpace != 'srgb') {
    throw const FormatException(
      'Only srgb color tokens can be emitted to CSS.',
    );
  }
  if (components is! List || components.length != 3) {
    throw const FormatException('srgb color components must have 3 values.');
  }
  if (alpha == 1 && hex is String) return hex.toUpperCase();

  final red = _componentToByte(components[0]);
  final green = _componentToByte(components[1]);
  final blue = _componentToByte(components[2]);
  return 'rgba($red, $green, $blue, ${_formatNumber(alpha)})';
}

int _componentToByte(Object? value) {
  if (value is! num) {
    throw const FormatException('srgb components must be numbers.');
  }
  return (value * 255).round().clamp(0, 255);
}

String _dimensionCssValue(Map<String, dynamic> value) {
  final number = value['value'];
  final unit = value['unit'];
  if (number is! num) {
    throw const FormatException('dimension value must be numeric.');
  }
  if (unit is! String || unit.isEmpty) {
    throw const FormatException('dimension unit must be a string.');
  }
  return '${_formatNumber(number)}$unit';
}

String _cssLength(num value) => value == 0 ? '0' : '${_formatNumber(value)}px';

final class _ShadowLayer {
  const _ShadowLayer({
    required this.color,
    required this.x,
    required this.y,
    required this.blur,
    required this.spread,
  });

  final Map<String, dynamic> color;
  final num x;
  final num y;
  final num blur;
  final num spread;
}

/// One or more DTCG shadow layers, each emitted as a CSS box-shadow layer and
/// a Flutter [BoxShadow] with the same offset, blur and spread numbers.
List<_ShadowLayer> _shadowLayers(Object? value) {
  final layers = value is List ? value : <Object?>[value];
  if (layers.isEmpty) {
    throw const FormatException('shadow needs at least one layer.');
  }
  return layers
      .map((raw) {
        final layer = _mapValue(raw, 'shadow layer');
        num px(String key) {
          final dimension = _mapValue(layer[key], 'shadow $key');
          final number = dimension['value'];
          if (dimension['unit'] != 'px' || number is! num) {
            throw FormatException('shadow $key must be a px dimension.');
          }
          return number;
        }

        return _ShadowLayer(
          color: _mapValue(layer['color'], 'shadow color'),
          x: px('offsetX'),
          y: px('offsetY'),
          blur: px('blur'),
          spread: px('spread'),
        );
      })
      .toList(growable: false);
}

/// Writes `dart format`-stable layers so the generated file survives the
/// pre-commit formatter unchanged.
void _writeDartShadowLayers(StringBuffer buffer, Object? value) {
  for (final layer in _shadowLayers(value)) {
    buffer
      ..writeln('    BoxShadow(')
      ..writeln('      color: ${_dartColorValue(layer.color)},')
      ..writeln('      blurRadius: ${_formatDartNumber(layer.blur)},');
    if (layer.spread != 0) {
      buffer.writeln('      spreadRadius: ${_formatDartNumber(layer.spread)},');
    }
    buffer
      ..writeln(
        '      offset: Offset(${_formatDartNumber(layer.x)}, '
        '${_formatDartNumber(layer.y)}),',
      )
      ..writeln('    ),');
  }
}

/// Mirrors `ActivitySwatch._derive` in `lib/platform/theme/activity_palette.dart`,
/// including Flutter's `HSLColor` math, so the website reads the same deep,
/// soft and dark-mode swatches the app derives at runtime.
/// `test/core/theme/activity_palette_web_parity_test.dart` fails on drift.
Map<String, String> _derivedActivitySwatches(Map<String, dynamic> pigment) {
  final hex = pigment['hex'];
  if (hex is! String) {
    throw const FormatException('activity pigments need a hex value.');
  }
  final color = _hexColorValue(hex)['components']! as List<num>;
  final hsl = _Hsl.fromRgb(
    color[0].toDouble(),
    color[1].toDouble(),
    color[2].toDouble(),
  );
  double unit(double value) => value.clamp(0.0, 1.0).toDouble();
  return <String, String>{
    'deep': hsl
        .copyWith(
          lightness: unit(hsl.lightness - 0.13),
          saturation: unit(hsl.saturation + 0.04),
        )
        .hex,
    'soft': hsl
        .copyWith(lightness: 0.93, saturation: unit(hsl.saturation * 0.55))
        .hex,
    'accent-dark': hsl.copyWith(lightness: unit(hsl.lightness + 0.07)).hex,
    'soft-dark': hsl
        .copyWith(lightness: 0.22, saturation: unit(hsl.saturation * 0.5))
        .hex,
  };
}

final class _Hsl {
  const _Hsl(this.hue, this.saturation, this.lightness);

  factory _Hsl.fromRgb(double red, double green, double blue) {
    final max = [red, green, blue].reduce((a, b) => a > b ? a : b);
    final min = [red, green, blue].reduce((a, b) => a < b ? a : b);
    final delta = max - min;
    var hue = 0.0;
    if (max == 0.0) {
      hue = 0.0;
    } else if (max == red) {
      hue = 60.0 * (((green - blue) / delta) % 6);
    } else if (max == green) {
      hue = 60.0 * (((blue - red) / delta) + 2);
    } else {
      hue = 60.0 * (((red - green) / delta) + 4);
    }
    if (hue.isNaN) hue = 0.0;
    final lightness = (max + min) / 2.0;
    final saturation = lightness == 1.0
        ? 0.0
        : (delta / (1.0 - (2.0 * lightness - 1.0).abs()))
              .clamp(0.0, 1.0)
              .toDouble();
    return _Hsl(hue, saturation, lightness);
  }

  final double hue;
  final double saturation;
  final double lightness;

  _Hsl copyWith({double? saturation, double? lightness}) =>
      _Hsl(hue, saturation ?? this.saturation, lightness ?? this.lightness);

  String get hex {
    final chroma = (1.0 - (2.0 * lightness - 1.0).abs()) * saturation;
    final secondary = chroma * (1.0 - (((hue / 60.0) % 2.0) - 1.0).abs());
    final match = lightness - chroma / 2.0;
    final (red, green, blue) = switch (hue) {
      < 60.0 => (chroma, secondary, 0.0),
      < 120.0 => (secondary, chroma, 0.0),
      < 180.0 => (0.0, chroma, secondary),
      < 240.0 => (0.0, secondary, chroma),
      < 300.0 => (secondary, 0.0, chroma),
      _ => (chroma, 0.0, secondary),
    };
    String channel(double value) => _hexByte(((value + match) * 255).round());
    return '#${channel(red)}${channel(green)}${channel(blue)}';
  }
}

String _rawCssValue(Object? value) {
  if (value is num) return _formatNumber(value);
  if (value is String) return value;
  throw FormatException('Cannot emit CSS value for $value.');
}

String _formatNumber(num value) {
  if (value == value.roundToDouble()) return value.toInt().toString();
  return value.toString();
}

bool _isReference(String value) =>
    value.startsWith('{') && value.endsWith('}') && value.length > 2;

String _referencePath(String value) => value.substring(1, value.length - 1);

/// Emit immutable profiles; the shared platform selector chooses one profile.
/// Fail generation on a missing role or invalid metric instead of silently
/// exporting an incomplete platform scale.
void _writePlatformTokens(StringBuffer buffer, _TokenRegistry registry) {
  final roles = registry.tokens.values
      .where(
        (t) =>
            t.path.length == 4 &&
            t.path[0] == 'typography' &&
            t.path[1] == 'ios',
      )
      .map((t) => t.path[2])
      .toSet();
  if (roles.isEmpty) {
    throw const FormatException('Missing typography profiles.');
  }
  final androidRoles = registry.tokens.values
      .where(
        (t) =>
            t.path.length == 4 &&
            t.path[0] == 'typography' &&
            t.path[1] == 'android',
      )
      .map((t) => t.path[2])
      .toSet();
  if (roles.length != androidRoles.length || !roles.containsAll(androidRoles)) {
    throw const FormatException('Typography platform roles must match.');
  }
  buffer
    ..writeln()
    ..writeln('@immutable')
    ..writeln('class GeneratedCatchTypographyProfile {')
    ..writeln('  const GeneratedCatchTypographyProfile({');
  for (final role in roles) {
    buffer.writeln('    required this.$role,');
  }
  buffer.writeln('  });');
  for (final role in roles) {
    buffer.writeln('  final TextStyle $role;');
  }
  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchTypographyTokens {');
  for (final platform in ['ios', 'android']) {
    buffer.writeln(
      '  static const $platform = GeneratedCatchTypographyProfile(',
    );
    for (final role in roles) {
      Object? metric(String key) {
        final path = 'typography.$platform.$role.$key';
        final token = registry.tokens[path];
        if (token == null) throw FormatException('Missing $path.');
        return registry.resolvedValue(token);
      }

      final size = _dartDimensionNumber(metric('size'));
      final line = _dartDimensionNumber(metric('lineHeight'));
      final tracking = _dartDimensionNumber(metric('tracking'));
      final weight = metric('weight');
      if (double.parse(size) <= 0 ||
          double.parse(line) < double.parse(size) ||
          weight is! int ||
          weight < 100 ||
          weight > 900 ||
          weight % 100 != 0) {
        throw FormatException('Invalid typography metrics: $platform.$role.');
      }
      buffer.writeln(
        '    $role: TextStyle(fontSize: $size, height: $line / $size, '
        'fontWeight: FontWeight.w$weight, letterSpacing: $tracking),',
      );
    }
    buffer.writeln('  );');
  }
  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchLayoutTokens {');
  for (final token in registry.tokens.values.where(
    (t) => t.path.length == 2 && t.path[0] == 'layout',
  )) {
    buffer.writeln(
      '  static const double ${token.path.last} = ${_dartDimensionNumber(registry.resolvedValue(token))};',
    );
  }
  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchInteractionTokens {');
  for (final token in registry.tokens.values.where(
    (t) => t.path.length == 3 && t.path[0] == 'interaction',
  )) {
    buffer.writeln(
      '  static const double ${_camel(token.path.skip(1))} = ${_dartDimensionNumber(registry.resolvedValue(token))};',
    );
  }
  buffer.writeln('}');
  _writeFoundationTokens(buffer, registry);
}

/// Only semantic foundations are emitted into the runtime API. Platform
/// reference tables remain authored source data; an explicit alias is required
/// to promote one of them into a Catch component contract.
void _writeFoundationTokens(StringBuffer buffer, _TokenRegistry registry) {
  buffer
    ..writeln()
    ..writeln('abstract final class GeneratedCatchMotionTokens {');
  for (final token in registry.tokens.values.where(
    (t) => t.path.length == 2 && t.path[0] == 'motion',
  )) {
    final value = registry.resolvedValue(token);
    if (token.type == 'duration') {
      final duration = _mapValue(value, token.referencePath);
      final ms = duration['value'];
      if (duration['unit'] != 'ms' || ms is! int || ms < 0) {
        throw FormatException('Invalid duration: ${token.referencePath}');
      }
      buffer.writeln(
        '  static const Duration ${token.path.last} = Duration(milliseconds: $ms);',
      );
    } else if (token.type == 'cubicBezier') {
      if (value is! List || value.length != 4 || value.any((v) => v is! num)) {
        throw FormatException('Invalid curve: ${token.referencePath}');
      }
      buffer.writeln(
        '  static const Curve ${token.path.last} = Cubic(${value.map((v) => _formatDartNumber(v as num)).join(', ')});',
      );
    } else {
      throw FormatException('Unsupported motion token: ${token.referencePath}');
    }
  }
  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchElevationTokens {');
  for (final token in registry.tokens.values.where(
    (t) => t.path.length == 2 && t.path[0] == 'elevation',
  )) {
    if (token.type != 'shadow') {
      throw FormatException(
        'Unsupported elevation token: ${token.referencePath}',
      );
    }
    buffer.writeln(
      '  static const List<BoxShadow> ${token.path.last} = <BoxShadow>[',
    );
    _writeDartShadowLayers(buffer, registry.resolvedValue(token));
    buffer.writeln('  ];');
  }
  buffer
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class GeneratedCatchAccessibilityTokens {');
  for (final token in registry.tokens.values.where(
    (t) => t.path.length == 2 && t.path[0] == 'accessibility',
  )) {
    final value = registry.resolvedValue(token);
    if (value is! num || value <= 0) {
      throw FormatException(
        'Invalid accessibility floor: ${token.referencePath}',
      );
    }
    buffer.writeln(
      '  static const double ${token.path.last} = ${_formatDartNumber(value)};',
    );
  }
  buffer.writeln('}');
  _writeDimensionGroup(buffer, registry, 'gap', 'GeneratedCatchGapTokens');
  _writeNumberGroup(buffer, registry, 'opacity', 'GeneratedCatchOpacityTokens');
  _writeNumberGroup(buffer, registry, 'field', 'GeneratedCatchFieldTokens');
  buffer
    ..writeln()
    ..writeln('abstract final class GeneratedCatchThemeElevationTokens {');
  for (final token in registry.tokens.values.where(
    (t) =>
        t.path.length == 4 && t.path[0] == 'theme' && t.path[2] == 'elevation',
  )) {
    if (token.type != 'shadow') {
      throw FormatException(
        'Unsupported theme elevation: ${token.referencePath}',
      );
    }
    buffer.writeln(
      '  static const List<BoxShadow> ${_dartThemeTokenName(token)} = <BoxShadow>[',
    );
    _writeDartShadowLayers(buffer, registry.resolvedValue(token));
    buffer.writeln('  ];');
  }
  buffer.writeln('}');
  _writeDimensionGroup(
    buffer,
    registry,
    'stroke',
    'GeneratedCatchStrokeTokens',
  );
  _writeDimensionGroup(
    buffer,
    registry,
    'windowSize',
    'GeneratedCatchWindowSizeTokens',
  );
}

/// A colour group at any depth, emitted as Colors named by their path below
/// the group: `ground.coral.inkSecondary` becomes `coralInkSecondary`.
void _writeColorGroup(
  StringBuffer buffer,
  _TokenRegistry registry,
  String group,
  String className,
) {
  final tokens = registry.tokens.values
      .where((t) => t.path.length > 1 && t.path[0] == group)
      .toList();
  if (tokens.isEmpty) throw FormatException('Missing $group tokens.');
  buffer
    ..writeln()
    ..writeln('abstract final class $className {');
  for (final token in tokens) {
    if (token.type != 'color') {
      throw FormatException('Unsupported $group token: ${token.referencePath}');
    }
    buffer.writeln(
      '  static const Color ${_camel(token.path.skip(1))} = '
      '${_dartColorValue(registry.resolvedValue(token))};',
    );
  }
  buffer.writeln('}');
}

