import assert from "node:assert/strict";
import test from "node:test";
import {
  areaReExports,
  checkDispatchRegistries,
  dispatcherName,
  findRegistrations,
  loadSourcesConfig,
  planDispatchRegistries,
  registryDrift,
} from "./generate_dispatch_registries.mjs";

const config = loadSourcesConfig(JSON.stringify({sources: {
  organizers: {document: "organizers/{organizerId}", area: "organizers"},
  events: {document: "events/{eventId}", area: "events"},
}}));

const reExport = 'export {dispatchOrganizers} from "./dispatch/organizers.generated";\n';

function files(extra = {}) {
  return new Map(Object.entries({
    "functions/src/organizers/functions.ts": reExport,
    "functions/src/organizers/publicOrganizerProjection.ts":
      'export const publicOrganizerProjections = defineProjections("organizers", [\n]);\n',
    "functions/src/hostReadModels/organizerViews.ts":
      'export const hostOrganizerViewProjections: ProjectionSet =\n  defineProjections("organizers", []);\n',
    "functions/src/hostReadModels/organizerViews.test.ts":
      'export const ignored = defineProjections("organizers", []);\n',
    ...extra,
  }));
}

test("reads the sources config and rejects malformed entries", () => {
  assert.deepEqual(config.map((source) => source.id), ["events", "organizers"]);
  assert.throws(() => loadSourcesConfig("{}"), /sources object/);
  assert.throws(() => loadSourcesConfig(JSON.stringify({sources: {
    Organizers: {document: "organizers/{id}", area: "organizers"}}})), /camelCase/);
  assert.throws(() => loadSourcesConfig(JSON.stringify({sources: {
    organizers: {document: "organizers", area: "organizers"}}})), /document path/);
  assert.throws(() => loadSourcesConfig(JSON.stringify({sources: {
    organizers: {document: "organizers/{id}", area: "nowhere"}}}),
  {areas: new Set(["organizers"])}), /no codebase/);
  assert.throws(() => loadSourcesConfig(JSON.stringify({sources: {
    organizers: {document: "organizers/{id}", area: "organizers", memory: "1GiB"}}})),
  /unknown keys/);
  assert.equal(dispatcherName("organizerPosts"), "dispatchOrganizerPosts");
});

test("generates one registry per source from the contexts' sets, in path order", () => {
  const {outputs, errors} = planDispatchRegistries({config, files: files()});
  assert.deepEqual(errors, []);
  // events has no registered set, so it gets no registry and no trigger.
  assert.deepEqual([...outputs.keys()],
    ["functions/src/organizers/dispatch/organizers.generated.ts"]);
  assert.equal(outputs.get("functions/src/organizers/dispatch/organizers.generated.ts"), [
    "/* eslint-disable max-len */",
    "// GENERATED by tool/architecture/generate_dispatch_registries.mjs from",
    "// functions/dispatch-sources.json; do not edit. The one trigger for",
    "// organizers/{organizerId} (issue #2451).",
    "import {dispatchTrigger} from",
    '  "../../platform/dispatch/runtime";',
    "import {hostOrganizerViewProjections} from",
    '  "../../hostReadModels/organizerViews";',
    "import {publicOrganizerProjections} from",
    '  "../publicOrganizerProjection";',
    "",
    'export const dispatchOrganizers = dispatchTrigger("organizers",',
    '  "organizers/{organizerId}", [',
    "  hostOrganizerViewProjections,",
    "  publicOrganizerProjections,",
    "  ]);",
    "",
  ].join("\n"));
});

test("a set for an unlisted source or a malformed call fails", () => {
  const {errors} = planDispatchRegistries({config, files: files({
    "functions/src/programs/programViews.ts":
      'export const programProjections = defineProjections("programs", []);\n',
    "functions/src/media/thumbnails.ts":
      'const local = defineProjections("organizers", []);\nexport {local};\n',
  })});
  assert.equal(errors.length, 2);
  assert.match(errors[0], /media\/thumbnails\.ts: call defineProjections only as/);
  assert.match(errors[1], /programs\/programViews\.ts: programProjections registers with source "programs"/);
  assert.equal(findRegistrations(files()).bySource.get("organizers").length, 2);
});

test("a registry its area entry does not re-export fails, so it cannot silently not deploy", () => {
  const {errors} = planDispatchRegistries({config,
    files: files({"functions/src/organizers/functions.ts": "export {other} from \"./other\";\n"})});
  assert.equal(errors.length, 1);
  assert.match(errors[0], /must re-export dispatchOrganizers/);
  assert.equal(areaReExports(
    'export {\n  createOrganizer,\n  dispatchOrganizers,\n} from "./dispatch/organizers.generated";',
    {id: "organizers"}), true);
  assert.equal(areaReExports('export {dispatchOrganizersX} from "./dispatch/organizers.generated";',
    {id: "organizers"}), false);
});

test("drift names missing, stale and orphaned registries", () => {
  const outputs = new Map([["functions/src/organizers/dispatch/organizers.generated.ts", "a"],
    ["functions/src/events/dispatch/events.generated.ts", "b"]]);
  const existing = new Map([["functions/src/organizers/dispatch/organizers.generated.ts", "old"],
    ["functions/src/programs/dispatch/programs.generated.ts", "c"]]);
  assert.deepEqual(registryDrift({outputs, existing}), [
    "functions/src/organizers/dispatch/organizers.generated.ts is stale",
    "functions/src/events/dispatch/events.generated.ts is missing",
    "functions/src/programs/dispatch/programs.generated.ts registers nothing; delete it",
  ]);
});

test("checks a repository snapshot end to end", () => {
  const texts = files({
    "functions/dispatch-sources.json": JSON.stringify({sources: {
      organizers: {document: "organizers/{organizerId}", area: "organizers"}}}),
    "functions/deploy-codebases.json": JSON.stringify({codebases: {organizers: ["organizers"],
      host: ["hostReadModels"]}}),
  });
  const snapshot = {
    readTexts: (paths) => new Map(paths.map((file) => [file, texts.get(file)])),
    listFiles: ({prefix}) => [...texts.keys()].filter((file) => file.startsWith(prefix)),
  };
  const result = checkDispatchRegistries({snapshot});
  assert.deepEqual(result.errors, []);
  assert.deepEqual(result.drift,
    ["functions/src/organizers/dispatch/organizers.generated.ts is missing"]);
  texts.set("functions/src/organizers/dispatch/organizers.generated.ts",
    result.outputs.get("functions/src/organizers/dispatch/organizers.generated.ts"));
  assert.deepEqual(checkDispatchRegistries({snapshot}).drift, []);
});
