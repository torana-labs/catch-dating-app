#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {fromRepo} from "../lib/repo_paths.mjs";
import {isPlannedWithoutDart} from "./component_concepts.mjs";
import {collectProductionWidgetClassificationDeclarations} from "./generate_widget_classification.mjs";
import {
  componentLevels as levels,
  featureWidgetNamingIssues,
  reservedPrefixSymbolProblems,
  roleNounRedirectAdvice,
  roleNouns,
  sharedWidgetLevel,
  topLevelDeclarations,
} from "./lib/component_naming.mjs";
import {isGeneratedProductionWidgetDartPath, productionWidgetRoots} from "./lib/production_widget_roots.mjs";

// The inventory is derived from live source and never committed: two pull
// requests that each add a Widget used to collide on one generated region.
// docs/widget_catalog.md holds only the authored usage decisions.
export const catalogOutputPath = "build/generated/widget_catalog.md";
export const namingBaselinePath = "design/components/widget_naming_baseline.json";

/** Preserve every public production Widget; registry metadata never filters it. */
export function buildCatalogRows({declarations, components}) {
  const identities = new Map();
  for (const component of components) {
    if (isPlannedWithoutDart(component)) continue;
    addIdentity(component.dart?.symbol, component.dart?.file, component);
    for (const member of component.contract?.members ?? []) {
      addIdentity(member.symbol, member.file ?? component.dart?.file, member);
    }
  }

  const seen = new Set();
  const rows = declarations
    .filter((entry) => entry.classKind === "widget" && entry.visibility === "public")
    .map((entry) => {
      const identity = `${entry.file}:${entry.name}`;
      if (seen.has(identity)) throw new Error(`Duplicate source declaration: ${identity}`);
      seen.add(identity);
      const record = identities.get(entry.name);
      if (record && record.file !== entry.file) {
        throw new Error(`${entry.name}: registry path ${record.file} differs from source ${entry.file}`);
      }
      const homeLevel = sharedWidgetLevel(entry.file);
      if (homeLevel && !record) {
        throw new Error(`${identity}: shared Widget has no component-registry identity`);
      }
      const hasReviewedMetadata = record?.level != null || record?.roleNoun != null;
      if ((homeLevel || hasReviewedMetadata) &&
          (!levels.includes(record?.level) || !roleNouns.includes(record?.roleNoun))) {
        throw new Error(`${identity}: registry level and roleNoun are required`);
      }
      if (homeLevel && record.level !== homeLevel) {
        throw new Error(`${identity}: registry level ${record.level} disagrees with source home ${homeLevel}`);
      }
      // Feature levels use the existing route/screen naming boundary. Registered
      // metadata remains authoritative for reviewed domain and adapter surfaces.
      const level = record?.level ?? (
        /(?:Screen|Page|Route|App)$/u.test(entry.name) ? "L6" : "L5"
      );
      const documentation = classPurpose(entry.source, entry.line);
      return {
        name: entry.name,
        file: entry.file,
        line: entry.line,
        level,
        roleNoun: record?.roleNoun ?? null,
        conceptId: record?.governance?.conceptId ?? null,
        purpose: documentation || record?.summary || null,
        purposeSource: documentation ? "class-doc" : record?.summary ? "registry" : "missing",
        aliases: record?.aliases ?? [],
      };
    });
  return rows.sort((a, b) =>
    compare(a.level, b.level) || compare(a.file, b.file) || compare(a.name, b.name));

  function addIdentity(symbol, file, record) {
    if (!symbol || !file) throw new Error(`${record.id}: registry symbol and file are required`);
    if (identities.has(symbol)) throw new Error(`Duplicate registry identity: ${symbol}`);
    identities.set(symbol, {...record, file});
  }
}

/** Read only documentation attached to this declaration, never a nearby field. */
export function classPurpose(source, line) {
  const before = source.split(/\r?\n/u).slice(0, line - 1).join("\n");
  const annotations = String.raw`(?:\s*@[A-Za-z_$][\w.$]*(?:\([^;{}]*\))?)*\s*(?![\s\S])`;
  const lineDoc = before.match(new RegExp(
    String.raw`((?:^[ \t]*\/\/\/[^\n]*(?:\n|$))+)${annotations}`, "mu",
  ));
  if (lineDoc) {
    return firstParagraph(lineDoc[1].split("\n").map((value) =>
      value.replace(/^[ \t]*\/\/\/[ ]?/u, "")));
  }
  const blockDoc = before.match(new RegExp(
    String.raw`\/\*\*((?:(?!\*\/)[\s\S])*)\*\/${annotations}`, "u",
  ));
  return blockDoc ? firstParagraph(blockDoc[1].split("\n").map((value) =>
    value.replace(/^\s*\* ?/u, "").trim())) : "";
}

export function renderCatalogInventory(rows) {
  const missing = rows.filter((row) => row.purposeSource === "missing").length;
  const output = [
    "<!-- Generated by tool/design/generate_widget_catalog.mjs --write from live source; not committed. -->",
    "# Production Widget Inventory",
    "",
    "Authored usage decisions live in docs/widget_catalog.md.",
    "",
    `${rows.length} public production Widgets. Source discovery determines membership; ` +
      "the component registry supplies reviewed identity and ladder metadata.",
    "",
    "Purpose comes from the first class documentation paragraph, then the registry summary. " +
      `${missing} declarations have neither and remain visible as undocumented. ` +
      "Unreviewed feature Widgets use the existing screen-name boundary for L5/L6; " +
      "that source classification is not a semantic conformance verdict.",
  ];
  for (const level of levels) {
    const entries = rows.filter((row) => row.level === level);
    if (entries.length === 0) continue;
    output.push("", `### ${level} (${entries.length})`, "",
      "| Widget | Source | Role | Canonical concept | Purpose |",
      "|---|---|---|---|---|");
    for (const entry of entries) {
      // File only: a line number would churn this region on every unrelated edit.
      output.push(`| ${code(entry.name)} | ${code(entry.file)} | ` +
        `${entry.roleNoun ? code(entry.roleNoun) : "—"} | ` +
        `${entry.conceptId ? code(entry.conceptId) : "—"} | ` +
        `${cell(entry.purpose ?? "No class documentation or registry summary.")}` +
        `${entry.aliases?.length ? ` Also called: ${entry.aliases.map(code).join(", ")}.` : ""} |`);
    }
  }
  output.push("");
  return output.join("\n");
}

/**
 * Feature-naming and reserved-prefix findings across production Dart. The
 * baseline may only shrink: new findings and fixed-but-listed findings fail.
 */
export function namingFindings({declarations, symbolDeclarations}) {
  const findings = new Map();
  const add = (file, name, issues) => {
    const key = `${file}::${name}`;
    const previous = findings.get(key)?.issues ?? [];
    findings.set(key, {file, name, issues: [...new Set([...previous, ...issues])].sort()});
  };
  for (const entry of declarations) {
    if (entry.classKind !== "widget" || entry.visibility !== "public") continue;
    const issues = featureWidgetNamingIssues(entry);
    if (issues.length > 0) add(entry.file, entry.name, issues);
  }
  for (const problem of reservedPrefixSymbolProblems(symbolDeclarations)) {
    add(problem.file, problem.name, problem.issues);
  }
  return [...findings.values()].sort((a, b) => compare(a.file, b.file) || compare(a.name, b.name));
}

// A carried file (tool/architecture/carried_screens.json) keeps the rules of
// the legacy path it moved from until its redraw, as the Catch lints and the
// library-shims gate read it, so its naming is judged at that path: a Phase 4
// move of lib/pages/frame/app.dart into lib/pages/frame/ adds no naming debt. Findings
// still name the file where it is now.
export function carriedNamingFindings({carried, declarations, symbolDeclarations}) {
  const asFrom = (entry) => (carried.has(entry.file) ? {...entry, file: carried.get(entry.file)} : entry);
  const back = new Map([...carried].map(([to, from]) => [from, to]));
  return namingFindings({
    declarations: declarations.map(asFrom),
    symbolDeclarations: symbolDeclarations.map(asFrom),
  }).map((finding) => (back.has(finding.file) ? {...finding, file: back.get(finding.file)} : finding))
    .sort((a, b) => compare(a.file, b.file) || compare(a.name, b.name));
}

function readCarried(repoRoot) {
  const file = path.join(repoRoot, "tool/architecture/carried_screens.json");
  if (!fs.existsSync(file)) return new Map();
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  return new Map((json.carried ?? []).map((entry) => [entry.path, entry.from]));
}

// Debt is keyed by symbol so moving a file never turns carried debt into new debt.
export function namingRatchetProblems({findings, baseline, redirects = {}}) {
  const allowed = new Map((baseline?.allowedFindings ?? []).map((entry) => [entry.name, entry]));
  const current = new Map(findings.map((finding) => [finding.name, finding]));
  const problems = [];
  for (const [key, finding] of current) {
    const added = finding.issues.filter((issue) => !(allowed.get(key)?.issues ?? []).includes(issue));
    if (added.length === 0) continue;
    const advice = roleNounRedirectAdvice(finding.name, redirects);
    problems.push(`${finding.file}: ${finding.name} [${added.join(", ")}] is new naming debt` +
      `${advice ? `; ${advice}` : ""}`);
  }
  for (const [key, entry] of allowed) {
    const fixed = entry.issues.filter((issue) => !(current.get(key)?.issues ?? []).includes(issue));
    if (fixed.length === 0) continue;
    problems.push(`${entry.file}: ${entry.name} [${fixed.join(", ")}] is fixed; ` +
      `run node tool/design/generate_widget_catalog.mjs --write to remove it from ${namingBaselinePath}`);
  }
  return problems.sort();
}

/** Write mode only removes fixed debt; it never admits a new finding. */
export function prunedNamingBaseline({findings, baseline}) {
  const current = new Map(findings.map((finding) => [finding.name, finding]));
  const allowedFindings = (baseline?.allowedFindings ?? []).flatMap((entry) => {
    const finding = current.get(entry.name);
    const issues = entry.issues.filter((issue) => finding?.issues.includes(issue));
    return issues.length > 0 ? [{...entry, file: finding.file, issues}] : [];
  });
  return {...baseline, allowedFindings};
}

export function buildWidgetCatalog({repoRoot = fromRepo(".")} = {}) {
  const registry = JSON.parse(fs.readFileSync(
    path.join(repoRoot, "design/components/catch.components.json"), "utf8"));
  return buildCatalogRows({
    declarations: collectProductionWidgetClassificationDeclarations({repoRoot}),
    components: registry.components ?? [],
  });
}

/**
 * Check enforces what the inventory encodes against live source: every shared
 * Widget has an exact registry identity, reviewed level and role, and the
 * naming ratchet holds. Write also prunes fixed naming debt and writes the
 * inventory to the ignored catalogOutputPath.
 */
export function runCatalog({repoRoot = fromRepo("."), mode = "check"} = {}) {
  if (!["check", "write", "json"].includes(mode)) throw new Error(`Unknown catalog mode: ${mode}`);
  const rows = buildWidgetCatalog({repoRoot});
  if (mode === "json") return {rows};
  runNamingRatchet({repoRoot, mode});
  if (mode === "write") {
    const file = path.join(repoRoot, catalogOutputPath);
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, renderCatalogInventory(rows));
  }
  return {count: rows.length, output: mode === "write" ? catalogOutputPath : null};
}

function runNamingRatchet({repoRoot, mode}) {
  const registry = JSON.parse(fs.readFileSync(
    path.join(repoRoot, "design/components/catch.components.json"), "utf8"));
  const findings = carriedNamingFindings({
    carried: readCarried(repoRoot),
    declarations: collectProductionWidgetClassificationDeclarations({repoRoot}),
    symbolDeclarations: productionDartFiles(repoRoot).flatMap((file) =>
      topLevelDeclarations(file, fs.readFileSync(path.join(repoRoot, file), "utf8"))),
  });
  const baselineFile = path.join(repoRoot, namingBaselinePath);
  const baseline = fs.existsSync(baselineFile) ? JSON.parse(fs.readFileSync(baselineFile, "utf8")) : null;
  if (mode === "write" && baseline) {
    const pruned = prunedNamingBaseline({findings, baseline});
    const text = `${JSON.stringify(pruned, null, 2)}\n`;
    if (text !== fs.readFileSync(baselineFile, "utf8")) fs.writeFileSync(baselineFile, text);
  }
  const current = fs.existsSync(baselineFile) ? JSON.parse(fs.readFileSync(baselineFile, "utf8")) : null;
  const problems = namingRatchetProblems({findings, baseline: current, redirects: registry.roleNounRedirects});
  if (problems.length > 0) {
    throw new Error(`Widget naming ratchet failed (${problems.length}):\n- ${problems.join("\n- ")}`);
  }
}

function productionDartFiles(repoRoot) {
  const files = [];
  const walk = (relative) => {
    const absolute = path.join(repoRoot, relative);
    if (!fs.existsSync(absolute)) return;
    for (const entry of fs.readdirSync(absolute, {withFileTypes: true})) {
      const child = path.posix.join(relative, entry.name);
      if (entry.isDirectory()) walk(child);
      else if (child.endsWith(".dart") && !isGeneratedProductionWidgetDartPath(child) &&
        !child.includes("/design_fixtures/")) files.push(child);
    }
  };
  for (const root of productionWidgetRoots) walk(root);
  return files.sort();
}

function firstParagraph(lines) {
  const result = [];
  for (const line of lines) {
    if (!line.trim() && result.length) break;
    if (line.trim()) result.push(line.trim());
  }
  return result.join(" ");
}

function cell(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;").replaceAll("|", "&#124;").replaceAll(/\s+/gu, " ").trim();
}
function code(value) { return `<code>${cell(value).replaceAll("`", "&#96;")}</code>`; }
function compare(a, b) { return a < b ? -1 : a > b ? 1 : 0; }

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.includes("--help")) {
      console.log("Usage: node tool/design/generate_widget_catalog.mjs [--check|--write|--json] [--repo-root <path>]");
    } else {
      let mode = "check";
      let selectedMode = false;
      let repoRoot = fromRepo(".");
      for (let i = 0; i < args.length; i += 1) {
        if (args[i] === "--repo-root" && args[i + 1] && !args[i + 1].startsWith("--")) {
          repoRoot = path.resolve(args[++i]);
        } else if (["--check", "--write", "--json"].includes(args[i]) && !selectedMode) {
          mode = args[i].slice(2);
          selectedMode = true;
        } else throw new Error(`Unknown, missing or conflicting argument: ${args[i]}`);
      }
      const result = runCatalog({repoRoot, mode});
      console.log(mode === "json" ? JSON.stringify(result, null, 2) :
        mode === "write" ? `Widget catalog inventory written to ${result.output} (${result.count} public Widgets).` :
          `Widget catalog check passed (${result.count} public Widgets).`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
