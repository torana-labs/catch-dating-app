#!/usr/bin/env node
// Writes the brand record into runtimes that cannot import packages/brand
// directly. Functions deploys only functions/; the website's release smoke runs
// its copy modules from a bare release worktree where only website/ resolves;
// Flutter reads a Dart class. It also rewrites the managed surfaces (see
// managed.mjs) when brand.json differs from applied.json.
// --check fails when an output is stale or a managed surface is not applied.
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {brand, brandConsistencyErrors} from "./index.mjs";
import {leaves, rewriteSurface, surfacePaths} from "./managed.mjs";

const packageDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(packageDir, "../..");
const appliedPath = path.join(packageDir, "applied.json");
const managedPath = path.join(packageDir, "managed_surfaces.json");
const header = [
  "// AUTO-GENERATED by packages/brand/generate.mjs",
  "// Source: packages/brand/brand.json",
  "// DO NOT EDIT DIRECTLY.",
].join("\n");

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\/]/gu, "\\$&");

export function renderFunctionsModule(record = brand) {
  return `${header}
/* eslint-disable max-len */

export const BRAND = ${JSON.stringify(record, null, 2)} as const;

/** An absolute URL on the public website. \`path\` starts with "/". */
export function brandWebUrl(path: \`/\${string}\` = "/"): string {
  return BRAND.web.origin + path;
}

/** The website origin escaped for use inside a RegExp source. */
export const BRAND_ORIGIN_PATTERN = ${JSON.stringify(escapeRegExp(record.web.origin))};
`;
}

export function renderWebsiteModule(record = brand) {
  return `${header}
// Website code imports the brand from here, never from @catch/brand: the
// release smoke runs website modules where no package is installed.

export const brand = ${JSON.stringify(record, null, 2)} as const;

const tokenPattern = /\\{\\{\\s*brand\\.([A-Za-z0-9_.]+)\\s*\\}\\}/gu;

function resolveBrandToken(path: string): string {
  let value: unknown = brand;
  for (const key of path.split(".")) {
    value = value !== null && typeof value === "object" && Object.hasOwn(value, key) ?
      (value as Record<string, unknown>)[key] : undefined;
  }
  if (typeof value !== "string") throw new Error(\`Unknown brand token: {{brand.\${path}}}\`);
  return value;
}

/** Resolves {{brand.*}} tokens; an unknown token throws. */
export function applyBrandText(text: string): string {
  return text.replace(tokenPattern, (_match, path: string) => resolveBrandToken(path));
}

/** Resolves brand tokens in every string of a JSON-like value. */
export function applyBrand<T>(value: T): T {
  if (typeof value === "string") return applyBrandText(value) as T;
  if (Array.isArray(value)) return value.map(applyBrand) as T;
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, applyBrand(child)])) as T;
  }
  return value;
}
`;
}

const camel = (keyPath) => keyPath.split(".").map((part, index) =>
  index === 0 ? part : part[0].toUpperCase() + part.slice(1)).join("");
const dartString = (value) => `'${value.replace(/\\/gu, "\\\\").replace(/'/gu, "\\'").replace(/\$/gu, "\\$")}'`;

function nullableLeaves(record, prefix = "") {
  return Object.entries(record).flatMap(([key, value]) => {
    const keyPath = prefix ? `${prefix}.${key}` : key;
    return value !== null && typeof value === "object" ? nullableLeaves(value, keyPath) : [[keyPath, value]];
  });
}

export function renderDartModule(record = brand) {
  // Matches dart format: a declaration over 80 columns breaks after "=".
  const fields = nullableLeaves(record).map(([keyPath, value]) => {
    const declaration = value === null ? `  static const String? ${camel(keyPath)} =` : `  static const ${camel(keyPath)} =`;
    const initializer = value === null ? "null" : dartString(value);
    const line = `${declaration} ${initializer};`;
    return line.length <= 80 ? line : `${declaration}\n      ${initializer};`;
  });
  return `${header}
final class Brand {
  const Brand._();

${fields.join("\n")}

  /// An absolute URL on the public website. [path] starts with "/".
  static Uri webUri(String path) => Uri.parse('$webOrigin$path');
}
`;
}

export function outputs(record = brand) {
  return [
    {path: "functions/src/shared/generated/brand.ts", content: renderFunctionsModule(record)},
    {path: "website/src/content/brand.ts", content: renderWebsiteModule(record)},
    {path: "lib/kernel/brand.dart", content: renderDartModule(record)},
  ];
}

function main() {
  const check = process.argv.includes("--check");
  const errors = brandConsistencyErrors();
  if (errors.length > 0) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  const stale = [];
  for (const output of outputs()) {
    const target = path.join(repoRoot, output.path);
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (current === output.content) continue;
    if (check) stale.push(output.path);
    else fs.writeFileSync(target, output.content);
  }
  const applied = JSON.parse(fs.readFileSync(appliedPath, "utf8"));
  const current = Object.fromEntries(Object.entries(brand));
  const unapplied = JSON.stringify(leaves(applied)) !== JSON.stringify(leaves(current));
  if (unapplied && check) stale.push("packages/brand/applied.json (managed surfaces still carry the previous brand)");
  if (unapplied && !check) {
    const {surfaces} = JSON.parse(fs.readFileSync(managedPath, "utf8"));
    const followUps = new Set();
    for (const surface of surfaces) {
      for (const file of surfacePaths(repoRoot, surface)) {
        const target = path.join(repoRoot, file);
        const before = fs.readFileSync(target, "utf8");
        const after = rewriteSurface(before, surface, applied, current);
        if (after !== before) {
          fs.writeFileSync(target, after);
          if (surface.then) followUps.add(surface.then);
        }
      }
    }
    fs.writeFileSync(appliedPath, `${JSON.stringify(current, null, 2)}\n`);
    if (followUps.size > 0) console.log(`Managed surfaces rewritten. Now run:\n${[...followUps].join("\n")}`);
  }
  if (stale.length > 0) {
    console.error(`Stale brand outputs:\n${stale.join("\n")}\nRun: node packages/brand/generate.mjs`);
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
